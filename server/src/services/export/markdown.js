import { fmtMeetingDate, fmtDue, STATUS_LABEL, PRIORITY_LABEL, refs } from './shared.js';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ');
const list = (items, empty, withOwner) =>
  items.length
    ? items
        .map((i) => `- ${i.text}${withOwner && i.owner ? ` — **${i.owner}**` : ''}${refs(i.segment_ids)}`)
        .join('\n')
    : `_${empty}_`;

export function buildMarkdown({ meeting, minutes, actionItems }) {
  const out = [];
  out.push(`# ${meeting.title}`, '');
  out.push(`**Date:** ${fmtMeetingDate(meeting.meetingDate)} (${meeting.timezone})  `);
  if (meeting.participants?.length) out.push(`**Participants:** ${meeting.participants.join(', ')}  `);
  out.push('_Generated by MinuteMate AI_', '');
  if (meeting.description) out.push(`> ${meeting.description}`, '');
  out.push('## Executive Summary', '', minutes?.overview || '_No summary available._', '');
  out.push('## Key Discussion Points', '', list(minutes?.keyPoints ?? [], 'None identified.'), '');
  out.push('## Decisions Made', '', list(minutes?.decisions ?? [], 'No confirmed decisions.', true), '');
  out.push('## Action Items', '');
  if (actionItems.length) {
    out.push('| Task | Assigned To | Due Date | Priority | Status |', '|---|---|---|---|---|');
    for (const a of actionItems) {
      out.push(
        `| ${cell(a.task)} | ${cell(a.assignee || 'Not assigned')} | ${cell(fmtDue(a.dueDate, a.originalDueDateText))} | ${PRIORITY_LABEL[a.priority]} | ${STATUS_LABEL[a.status]} |`,
      );
    }
  } else out.push('_No action items._');
  out.push('', '## Risks and Blockers', '', list(minutes?.risks ?? [], 'None identified.'), '');
  out.push('## Open Questions', '', list(minutes?.openQuestions ?? [], 'None identified.'), '');
  return out.join('\n');
}
